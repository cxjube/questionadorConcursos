"""Render a validated, deterministic catalog as a browser classic script."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


def render(catalog: dict) -> str:
    """Embed canonical JSON with a content revision and safe script delimiters."""
    canonical = json.dumps(catalog, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False)
    revision = hashlib.sha256(canonical.encode('utf-8')).hexdigest()
    payload = {'revision': revision, **catalog}
    encoded = json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False)
    encoded = encoded.replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    return '// Generated by python -m tools build. Do not edit.\nwindow.CONCURSOS_CATALOG = ' + encoded + ';\n'


def write_artifact(path: Path, content: str) -> None:
    """Replace the artifact only after its complete contents are available."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix('.tmp')
    temporary.write_text(content, encoding='utf-8', newline='\n')
    temporary.replace(path)


def render_logistics(data: dict) -> str:
    """Keep operational dates sourced in JSON without revising saved question snapshots."""
    encoded = json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False)
    encoded = encoded.replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    return '// Generated by python -m tools build. Do not edit.\nwindow.CONCURSOS_LOGISTICS = ' + encoded + ';\n'
